# 当前 BuiltinRules 里的短信规则（与 Kotlin 保持一致）
RULES = [
    ("sms_negative_amount_expense", r"-\s*([\d,]+\.?\d*)\s*元", "EXPENSE", 35),
    ("sms_expense", r"(?:支出|消费|付款|转出|扣款|取现|支取|现支|取款|取出|取)\s*(?:金额)?\s*(?:人民币|RMB|¥|￥)?\s*([\d,]+\.?\d*)\s*元?", "EXPENSE", 30),
    ("sms_income", r"(?:收入|存款|存入|转入|到账|退款|入账|存|收)\s*(?:金额)?\s*(?:人民币|RMB|¥|￥)?\s*([\d,]+\.?\d*)\s*元?", "INCOME", 30),
    ("sms_expense_plain", r"(?:支出|消费|扣款|转出)\s*(?:金额)?\s*[¥￥]?\s*([\d,]+\.?\d*)\s*元", "EXPENSE", 20),
    ("sms_income_plain", r"(?:收入|转入|存入|到账|退款)\s*(?:金额)?\s*[¥￥]?\s*([\d,]+\.?\d*)\s*元", "INCOME", 20),
    ("sms_repayment", r"(?:还款|已还|偿还)\s*(?:金额)?\s*(?:人民币)?\s*[¥￥]?\s*([\d,]+\.?\d*)\s*元", "NEUTRAL", 25),
    ("sms_transfer_neutral", r"(?:提现|充值|转存|转账)\s*(?:金额)?\s*(?:人民币)?\s*[¥￥]?\s*([\d,]+\.?\d*)\s*元", "NEUTRAL", 22),
]
RULES.sort(key=lambda r: -r[3])


def normalize(t):
    for a, b in [("\u00a0", " "), ("\u3000", " "), ("\uff0d", "-"), ("\uff1a", ":"),
                 ("\u2013", "-"), ("\u2014", "-"), ("\r\n", " "), ("\n", " ")]:
        t = t.replace(a, b)
    return re.sub(r"\s+", " ", t).strip()


def parse(text):
    n = normalize(text)
    for rid, pat, direction, _ in RULES:
        m = re.search(pat, n)
        if m:
            amt = float(m.group(1).replace(",", ""))
            if amt > 0:
                return rid, amt, direction
    return None


print(f"{'银行':<10} {'方向':<8} {'原文摘要':<46} {'结果'}")
print("=" * 118)
ok = fail = 0
failures = []
for bank, expect_dir, text in REAL_SAMPLES:
    r = parse(text)
    short = text[:44].replace("\n", " ")
    if r is None:
        print(f"{bank:<10} {expect_dir:<8} {short:<46} ❌ 未识别")
        fail += 1
        failures.append((bank, expect_dir, text))
    else:
        rid, amt, direction = r
        good = (direction == expect_dir)
        mark = "✅" if good else "⚠️ 方向错"
        print(f"{bank:<10} {expect_dir:<8} {short:<46} {mark} {amt} [{rid}]")
        if good:
            ok += 1
        else:
            fail += 1
            failures.append((bank, expect_dir, text))

print("=" * 118)
print(f"识别成功 {ok} / {ok+fail}    失败 {fail}")
if failures:
    print("\n需要补规则的样本：")
    for bank, d, t in failures:
        print(f"  [{bank} {d}] {t}")
